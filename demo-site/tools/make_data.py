"""Build src/data.js from the FAKE demo inventory, so the site shows what the agent knows.

python3 tools/make_data.py ../backend/sample_data/kolkata src/data.js
"""

import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

src, out = Path(sys.argv[1]), Path(sys.argv[2])


def rows(name: str) -> list[dict[str, str]]:
    with (src / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def lakh(inr: int) -> str:
    if inr >= 10_000_000:
        return f"₹{inr / 10_000_000:.2f}".rstrip("0").rstrip(".") + " Cr"
    return f"₹{round(inr / 100_000)} L"


types = defaultdict(list)
for t in rows("unit_types.csv"):
    types[t["project_code"]].append(t)
prices = {(p["project_code"], p["unit_type_code"]): p for p in rows("price_lists.csv")}
available = defaultdict(int)
for u in rows("units.csv"):
    if u["availability"] == "available":
        available[(u["project_code"], u["unit_type_code"])] += 1
amenities = defaultdict(list)
for a in rows("amenities.csv"):
    amenities[a["project_code"]].append(a["name"])
offers = {o["project_code"]: o["title"] for o in rows("offers.csv")}

projects = []
for p in rows("projects.csv"):
    homes = []
    for t in types[p["project_code"]]:
        price = prices.get((p["project_code"], t["unit_type_code"]))
        if not price:
            continue
        homes.append({
            "name": t["name"], "type": t["property_type"], "bhk": int(t["bhk"]),
            "sqft": int(t["carpet_area_sqft"]), "min": int(price["base_price_inr"]),
            "max": int(price["price_max_inr"]),
            "available": available[(p["project_code"], t["unit_type_code"])],
        })
    if not homes:
        continue
    low = min(h["min"] for h in homes)
    projects.append({
        "code": p["project_code"], "name": p["name"].replace(" (Sample)", ""),
        "area": p["locality"], "possession": p["possession_date"],
        "about": p["description"].replace("SAMPLE DATA for testing. Not a real development. ", ""),
        "from": low, "fromText": lakh(low), "bhks": sorted({h["bhk"] for h in homes}),
        "kinds": sorted({h["type"] for h in homes}), "homes": homes,
        "amenities": amenities[p["project_code"]], "offer": offers.get(p["project_code"]),
    })
projects.sort(key=lambda x: x["from"])
out.write_text("// Generated by tools/make_data.py from backend/sample_data/kolkata (FAKE data).\n"
               "export const PROJECTS = " + json.dumps(projects, ensure_ascii=False, indent=1) + ";\n",
               encoding="utf-8")
print(f"{len(projects)} projects written to {out}")
